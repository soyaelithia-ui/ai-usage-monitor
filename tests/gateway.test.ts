import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import type { AddressInfo } from 'node:net';
import { createApp } from '../server/app.js';
import { createGateway } from '../server/gateway.js';
import { loadPricing } from '../server/pricing.js';
import { UsageStore } from '../server/store.js';

test('gateway permite lectura pública, protege la ingesta y transmite SSE sin añadir CORS', { timeout: 10000 }, async t => {
  const catalog = loadPricing('config/pricing.json');
  const store = new UsageStore(':memory:', catalog);
  const app = createApp({ store, catalog, now: () => new Date('2026-10-28T12:00:00Z') });
  const upstream = app.app.listen(0, '127.0.0.1');
  await once(upstream, 'listening');
  const token = 'una-clave-de-prueba-con-mas-de-32-caracteres';
  const gateway = createGateway({ upstreamPort: (upstream.address() as AddressInfo).port, token });
  gateway.listen(0, '127.0.0.1');
  await once(gateway, 'listening');
  const base = `http://127.0.0.1:${(gateway.address() as AddressInfo).port}`;
  const abort = new AbortController();
  t.after(async () => {
    abort.abort(); app.closeStreams(); gateway.closeAllConnections(); upstream.closeAllConnections();
    await Promise.all([new Promise<void>(resolve => gateway.close(() => resolve())), new Promise<void>(resolve => upstream.close(() => resolve()))]);
    store.close();
  });
  const origin = 'https://remote.example';
  const health = await fetch(`${base}/api/health`, { headers: { Origin: origin } });
  assert.equal(health.status, 200);
  assert.equal(health.headers.get('access-control-allow-origin'), null);
  assert.equal((await fetch(`${base}/api/usage`, { method: 'DELETE' })).status, 405);
  const body = JSON.stringify({ agent_name: 'remote', model: 'gpt-6.1-sol', prompt_tokens: 1000, completion_tokens: 500 });
  const headers = { 'Content-Type': 'application/json', Origin: origin };
  assert.equal((await fetch(`${base}/api/usage`, { method: 'POST', headers, body })).status, 401);
  assert.equal((await fetch(`${base}/api/usage`, { method: 'POST', headers: { ...headers, Authorization: 'Bearer incorrecta' }, body })).status, 401);
  assert.equal(store.summary().totals.requests, 0);

  const response = await fetch(`${base}/api/stream`, { headers: { Origin: origin }, signal: abort.signal });
  const reader = response.body!.getReader();
  let received = '';
  const decoder = new TextDecoder();
  while (!received.includes('event: snapshot')) received += decoder.decode((await reader.read()).value);
  const start = performance.now();
  const created = await fetch(`${base}/api/usage`, { method: 'POST', headers: { ...headers, Authorization: `Bearer ${token}` }, body });
  assert.equal(created.status, 201);
  while (!received.includes('event: usage')) received += decoder.decode((await reader.read()).value);
  assert.ok(performance.now() - start < 1000);
  assert.match(received, /"cost_usd":"0\.007"/);
  assert.equal(store.summary().totals.requests, 1);
  await reader.cancel();
});
